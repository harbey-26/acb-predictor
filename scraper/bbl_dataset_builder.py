def parse_entry(entry: str):
    """Parse 'code:score' entry. Returns (date, home_id, away_id, pts_home, pts_away) or None."""
    entry = entry.strip()
    if not entry or ':' not in entry:
        return None
    code, score_s = entry.rsplit(':', 1)
    parts = score_s.split('-')
    if len(parts) != 2:
        return None
    try:
        s1, s2 = int(parts[0]), int(parts[1])
    except ValueError:
        return None

    if code.startswith('N_'):
        # NEW format: N_YYYY_MMDD_homeid_awayid → score = home-away
        rest = code[2:]
        m = re.match(r'^(\d{4})_(\d{4})_(\d+)_(\d+)$', rest)
        if not m:
            return None
        year, mmdd, home_id, away_id = m.groups()
        pts_home, pts_away = s1, s2
    else:
        # OLD format: YYYY_MMDD_awayid_homeid → score = away-home
        m = re.match(r'^(\d{4})_(\d{4})_(\d+)_(\d+)$', code)
        if not m:
            return None
        year, mmdd, away_id, home_id = m.groups()
        pts_home, pts_away = s2, s1

    year = int(year)
    month = int(mmdd[:2])
    day = int(mmdd[2:])
    home_id = int(home_id)
    away_id = int(away_id)
    game_date = date(year, month, day)
    return game_date, home_id, away_id, pts_home, pts_away


def get_season(d: date):
    for season, start, end in SEASON_BOUNDS:
        if start <= d <= end:
            return season
    return None


def build_matches():
    rows = []
    seen = set()

    for season_key, raw in RAW_GAMES.items():
        for line in raw.strip().splitlines():
            result = parse_entry(line)
            if result is None:
                continue
            game_date, home_id, away_id, pts_home, pts_away = result
            season = get_season(game_date)
            if season is None:
                season = season_key

            game_id = f"{game_date.year}_{game_date.month:02d}{game_date.day:02d}_{away_id}_{home_id}"
            if game_id in seen:
                continue
            seen.add(game_id)

            home_name = TEAM_NAMES.get(home_id, f"Team_{home_id}")
            away_name = TEAM_NAMES.get(away_id, f"Team_{away_id}")
            ganador = "local" if pts_home > pts_away else "visitante"
            is_playoff = 1 if game_date >= PLAYOFF_STARTS[season] else 0

            rows.append({
                "game_id": game_id,
                "fecha": f"{game_date.isoformat()}T00:00:00+00:00",
                "equipo_local": home_name,
                "club_local_id": home_id,
                "equipo_visitante": away_name,
                "club_visitante_id": away_id,
                "pts_local": pts_home,
                "pts_visitante": pts_away,
                "ganador": ganador,
                "temporada": season,
                "is_playoff": is_playoff,
            })

    rows.sort(key=lambda r: r["fecha"])
    return rows


def main():
    rows = build_matches()
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)

    fieldnames = ["game_id", "fecha", "equipo_local", "club_local_id",
                  "equipo_visitante", "club_visitante_id", "pts_local",
                  "pts_visitante", "ganador", "temporada", "is_playoff"]

    with open(OUTPUT_PATH, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    total = len(rows)
    regular = sum(1 for r in rows if r["is_playoff"] == 0)
    print(f"Wrote {total} games ({regular} regular season) to {OUTPUT_PATH}")
    by_season = {}
    for r in rows:
        by_season.setdefault(r["temporada"], 0)
        by_season[r["temporada"]] += 1
    for s in sorted(by_season):
        print(f"  {s}: {by_season[s]} games")


if __name__ == "__main__":
    main()
